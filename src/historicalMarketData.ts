// One entry per calendar year: the S&P 500's total return (price change plus
// dividends reinvested) and the year-over-year change in the US CPI-U — the
// pair simulation.ts bootstraps from to draw a "what markets actually did"
// sequence instead of a single flat assumption. Figures are commonly-cited
// reference numbers assembled from memory (in the spirit of published
// sources like the Ibbotson/SBBI series, Robert Shiller's dataset, and
// Damodaran's NYU Stern data library), not pulled from a live feed — treat
// them as good enough to illustrate sequence-of-returns risk, not as an
// audited historical record. Worth checking against a primary source before
// leaning on this for a real financial decision, the same caveat that
// applies to the RMD divisor table in types.ts.
